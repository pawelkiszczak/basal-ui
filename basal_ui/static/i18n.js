function fill(text, vars) {
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => Object.hasOwn(vars, k) ? String(vars[k]) : m) : text;
}
function t(text, vars) {
  return fill(LANG === 'pl' && Object.hasOwn(PL, text) ? PL[text] : text, vars);
}
function ts(text, code, params) {
  const translated = LANG === 'pl' && PL[`code:${code}`];
  const values = LANG === 'pl' && params
    ? {...params,
       ...(params.memory === null ? {memory: '—'} : {}),
       ...(params.estimate === null ? {estimate: '—'} : {}),
       ...(Array.isArray(params.kinds)
         ? {kinds: params.kinds.map(kind => ({image: 'obrazy', audio: 'audio'}[kind] || kind)).join(' i ')}
         : {})}
    : params;
  const result = fill(translated || text || '', values);
  return params?.estimate === null ? result.replace('— GB', '—') : result;
}
function plForm(n) {  // Polish: 1 model, 2-4 modele (not 12-14), 5+ modeli
  const a = Math.abs(n) % 100, b = a % 10;
  return n === 1 ? 0 : b >= 2 && b <= 4 && !(a >= 12 && a <= 14) ? 1 : 2;
}
function tp(n, one, other, vars) {
  const forms = LANG === 'pl' && PL_PLURAL[one];
  return fill(forms ? forms[plForm(Number(n))] : Number(n) === 1 ? one : other, {n, ...vars});
}
function translateStatic(root) {
  if (LANG === 'en') return;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node; (node = walk.nextNode());) {
    const text = node.nodeValue.trim();
    if (text && Object.hasOwn(PL, text)) node.nodeValue = node.nodeValue.replace(text, PL[text]);
  }
  for (const attr of ['title', 'placeholder', 'aria-label'])
    for (const el of root.querySelectorAll(`[${attr}]`)) {
      const text = el.getAttribute(attr).trim();
      if (Object.hasOwn(PL, text)) el.setAttribute(attr, PL[text]);
    }
}

